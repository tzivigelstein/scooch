// «घर पर स्टिकर प्रिंट करें» (print stickers at home): a sheet of stickers,
// each with the contour cut line (कंटूर), what it needs (transparency) and
// what the PDF's line is: a printed vector stroke to cut by hand, with no
// layer of its own and no registration marks (services/pdf.ts, core/contour.js).
// «आकृति» is a shape; «आकार» stays the size, as on the other pages.

