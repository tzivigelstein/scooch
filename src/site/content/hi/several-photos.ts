// «एक पेज पर कई फ़ोटो प्रिंट करें»: the main guide. The title says «पेज», as
// people search it; the page says «शीट», the app's word.

import { severalPhotosFacts } from '../../facts/several-photos.ts';
import { guide } from '../../guide.ts';
import { app, link, MAX_ITEMS, paragraphs, sheetFigure, steps, table, type Kit } from '../../kit.ts';
import type { SitePage } from '../../types.ts';
import { q } from './chrome.ts';
import { PATHS } from './paths.ts';

export function severalPhotos(k: Kit): SitePage {
  const { ui, num, mm, size, photoName, paperName } = k;
  const f = severalPhotosFacts();
  return guide({
    id: 'several-photos',
    lang: 'hi',
    path: PATHS['several-photos'],
    title: `एक पेज पर कई फ़ोटो प्रिंट करें, असली आकार में · ${app}`,
    description: `A4, ${paperName('letter')} या ${paperName('legal')} शीट पर कई फ़ोटो उनके असली आकार में रखें और PDF डाउनलोड या प्रिंट करें। मुफ़्त, बिना अकाउंट और बिना फ़ोटो अपलोड किए।`,
    h1: 'एक पेज पर कई फ़ोटो प्रिंट करें',
    crumb: 'एक पेज पर कई फ़ोटो',
    lead: `${app} से आप एक ही शीट पर कई फ़ोटो रख सकते हैं, हर फ़ोटो अपने असली आकार में, और कंप्यूटर या मोबाइल के ब्राउज़र से उन्हें एक साथ प्रिंट कर सकते हैं। यह मुफ़्त है, इसके लिए अकाउंट नहीं चाहिए और आपकी फ़ोटो आपके डिवाइस से बाहर नहीं जातीं।`,
    ctas: [
      { label: `A4 शीट के साथ ${app} खोलें`, href: f.open.a4 },
      { label: `${paperName('letter')} शीट के साथ खोलें`, href: f.open.letter },
    ],
    feature: sheetFigure(f.figure, `A4 शीट पर ${photoName(f.figure.photo)} की ${num(f.figure.count)} फ़ोटो, ${mm(f.layout.margin)} मार्जिन के साथ`),
    sections: [
      {
        h2: 'कैसे करें',
        html: steps([
          `${app} को उस कागज़ के साथ खोलें जिस पर आप प्रिंट करेंगे। कोई दूसरा कागज़ हो, तो उसे ${ui('props.title')} के ${ui('props.tabs.project')} टैब में बदलें: वहां A4, ${paperName('letter')}, ${paperName('legal')}, फ़ोटो पेपर और कस्टम आकार हैं।`,
          `${q(ui('bar.add'))} दबाएं या फ़ोटो को शीट पर छोड़ें। आप एक साथ कई फ़ोटो जोड़ सकते हैं, और PDF भी: उसका हर पेज एक अलग आइटम बनता है।`,
          `${q(ui('bar.arrange'))} दबाएं: ${app} सभी फ़ोटो को बिना ओवरलैप के रखता है और ज़रूरत के हिसाब से नई शीटें जोड़ता है।`,
          `अगर आप चाहते हैं कि सभी फ़ोटो एक ही आकार की हों, तो उन्हें चुनें और ${ui('crop.size')} चुनें (${photoName('10x15')}, ${photoName('13x18')}, ${photoName('id-4x4')}…) या चौड़ाई और ऊंचाई लिखें।`,
          `${q(ui('bar.print'))} या ${q(ui('bar.download'))} दबाएं। प्रिंट डायलॉग में “असली आकार” या “100%” चुनें, ताकि हर फ़ोटो अपने आकार में प्रिंट हो।`,
        ]),
      },
      {
        h2: 'एक शीट पर कितनी फ़ोटो आती हैं',
        html:
          paragraphs(`यह फ़ोटो के आकार, कागज़ और आपके प्रिंटर के छोड़े गए मार्जिन पर निर्भर करता है। ${q(ui('bar.arrange'))} हर शीट पर एक जैसी इतनी फ़ोटो रखता है:`) +
          table(
            [{ head: 'फ़ोटो' }, ...f.papers.map((p) => ({ head: paperName(p), num: true }))],
            f.rows.map((r) => [`${photoName(r.id)} <span class="muted">(${size(r.w, r.h)})</span>`, ...r.counts.map((n) => num(n))]),
            `${mm(f.layout.margin)} मार्जिन, फ़ोटो के बीच ${mm(f.layout.gap)} अंतराल और ${q(ui('props.rotate'))} चालू होने पर।`
          ) +
          paragraphs(`दूसरे आकार और मार्जिन के लिए ${link(PATHS['how-many'], 'कितनी फ़ोटो आएंगी, यह बताने वाला कैलकुलेटर')} इस्तेमाल करें।`),
      },
      {
        h2: 'असली आकार में, बिना छोटा-बड़ा किए',
        html: paragraphs(
          `${app} शीट के बिल्कुल सही आकार की PDF बनाता है, और हर फ़ोटो का आकार मिलीमीटर में रहता है, पिक्सल में नहीं। आकार अगर बदलता है, तो प्रिंट डायलॉग की वजह से: “पेज में फ़िट करें” या ऐसे किसी विकल्प से प्रिंटर सब कुछ थोड़ा छोटा कर देता है। इसलिए “असली आकार” या “100%” चुनें और ज़्यादा कॉपियां प्रिंट करने से पहले एक टेस्ट प्रिंट निकाल लें।`,
          `ज़्यादा जानकारी ${link(PATHS['actual-size'], 'इमेज को असली आकार में प्रिंट करने')} की गाइड में है।`
        ),
      },
      {
        h2: 'मोबाइल से',
        html: paragraphs(
          `${app} मोबाइल या टैबलेट के ब्राउज़र में चलता है, कुछ भी इंस्टॉल किए बिना। गैलरी से फ़ोटो जोड़ें, ${q(ui('bar.arrange'))} दबाएं और PDF डाउनलोड करें, फिर उसे खुद प्रिंट करें या प्रिंट करवाने के लिए किसी दुकान पर ले जाएं।`
        ),
      },
    ],
    faq: [
      { q: 'क्या मोबाइल से एक पेज पर कई फ़ोटो प्रिंट कर सकते हैं?', a: `हां। ${app} मोबाइल के ब्राउज़र में चलता है: गैलरी से फ़ोटो जोड़ें, ${q(ui('bar.arrange'))} दबाएं और PDF डाउनलोड करें।` },
      { q: 'क्या इसके लिए Word या कोई दूसरा सॉफ़्टवेयर चाहिए?', a: 'नहीं। सब कुछ ब्राउज़र में होता है: न कुछ इंस्टॉल करना है, न अकाउंट बनाना है।' },
      {
        q: 'प्रिंट करने पर फ़ोटो छोटी क्यों आती हैं?',
        a: 'लगभग हमेशा इसकी वजह प्रिंट डायलॉग का स्केल होता है। “पेज में फ़िट करें” या ऐसे किसी विकल्प से प्रिंटर शीट को छोटा कर देता है, ताकि वह उसके प्रिंट होने वाले हिस्से में आ जाए। “असली आकार” या “100%” चुनें।',
      },
      {
        q: 'क्या मेरी फ़ोटो किसी सर्वर पर अपलोड होती हैं?',
        a: `नहीं। फ़ोटो आपके ब्राउज़र में ही खुलती और प्रोसेस होती हैं, और PDF भी वहीं बनती है। ${link(PATHS['legal-privacy'], ui('legal.privacy'))} में इसकी जानकारी है।`,
      },
      { q: 'क्या अलग-अलग आकार की फ़ोटो, या फ़ोटो और PDF के पेज एक साथ रख सकते हैं?', a: `हां। ${q(ui('bar.arrange'))} किसी भी आकार के आइटम एक साथ रखता है, और PDF का हर पेज एक अलग आइटम होता है।` },
      { q: 'क्या वॉटरमार्क लगता है या फ़ोटो की कोई सीमा है?', a: `वॉटरमार्क नहीं लगता। एक प्रोजेक्ट में ${num(MAX_ITEMS)} आइटम तक हो सकते हैं।` },
    ],
  });
}
